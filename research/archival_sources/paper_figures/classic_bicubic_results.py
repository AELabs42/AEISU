"""Generate the classic bicubic quality table from the completed local campaign."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "output/training_campaigns/div2k_l1_3000_2026-10-17/evaluations/classic_219_mixed"
SETS = ("Set5", "Set14", "BSD100", "Urban100")
METHODS = (
    ("bilinear", "Bilinear"), ("fsr1_easu", "FSR1 EASU"), ("fsrcnn_x2", "FSRCNN"),
    ("repnet_x2", "RepNet"), ("rt4ksr_x2", "RT4KSR"), ("quicksrnet_small_x2", "QuickSRNet S"),
    ("quicksrnet_medium_x2", "QuickSRNet M"), ("span_x2", "SPAN"), ("swinir_light_x2", "SwinIR-Light"),
    ("aeisu_div2k_l1_3000_fp16", r"\model{} FP16"),
    ("aeisu_div2k_l1_3000_mixed", r"\model{} mixed"),
)


def main():
    summary = json.loads((SOURCE / "summary.json").read_text())
    verification = json.loads((SOURCE / "verification.json").read_text())
    assert summary["complete"] and verification["passed"] and verification["all_output_hashes_verified"]
    assert summary["images"] == summary["new_reconstructions"] == verification["records"] == 219
    lines = [
        r"% Generated by tools/paper_figures/classic_bicubic_results.py; numerical values from summary.json.",
        r"\begin{table*}[t]", r"\centering", r"\begingroup\fontsize{8}{9.5}\selectfont\setlength{\tabcolsep}{2.5pt}",
        r"\caption{Classic bicubic $2\times$ reconstruction. Dataset means of encoded-Y PSNR (P, dB), Y SSIM (S), "
        r"and RGB LPIPS (L), after a two-HR-pixel border crop. All metrics are recomputed from RGB outputs. "
        r"Both \model{} rows use the DIV2K L1 checkpoint trained for 3,000 epochs (915,000 updates): "
        r"FP16 is the common FP16-controller/FP32-reconstruction path; mixed is the native FP8/FP16 deployment. "
        r"Released comparators retain their recorded precision and training.}",
        r"\label{tab:classic-bicubic}", r"\begin{tabular}{l*{12}{r}}", r"\toprule",
        r" & \multicolumn{3}{c}{Set5 (5)} & \multicolumn{3}{c}{Set14 (14)} "
        r"& \multicolumn{3}{c}{B100 (100)} & \multicolumn{3}{c}{Urban100 (100)}\\",
        r"Method & P & S & L & P & S & L & P & S & L & P & S & L\\", r"\midrule",
    ]
    for method, label in METHODS:
        if method == "aeisu_div2k_l1_3000_fp16":
            lines.append(r"\midrule")
        values = []
        for dataset in SETS:
            mean = summary["means"][dataset][method]
            values += [f"{mean['y_psnr_shave2_db']:.3f}", f"{mean['y_ssim_shave2']:.5f}".lstrip("0"),
                       f"{mean['lpips_alex_v01']:.5f}".lstrip("0")]
        lines.append(label + " &" + "&".join(values) + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\endgroup", r"\end{table*}", ""]
    destination = ROOT / "docs/manuscript/figures/classic_bicubic.tex"
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {destination}: 132 quality cells")
    lines = [r"% Generated by tools/paper_figures/classic_bicubic_results.py.",
             r"\begin{table}[t]", r"\centering\small",
             r"\caption{DIV2K training comparison. MSE: 1,000 epochs/305,000 updates; L1: 3,000 epochs/915,000 updates. "
             r"P: Y PSNR (dB); S: Y SSIM; L: RGB LPIPS. Both checkpoints use the same evaluation path.}",
             r"\label{tab:div2k-training}", r"\begin{tabular}{lrrr}", r"\toprule", r"Dataset / loss & P & S & L\\", r"\midrule"]
    for dataset in SETS:
        display = "B100" if dataset == "BSD100" else dataset
        for method, loss in (("aeisu_div2k_fp16", "MSE"), ("aeisu_div2k_l1_3000_fp16", "L1")):
            v = summary["means"][dataset][method]
            lines.append(f"{display} {loss} &{v['y_psnr_shave2_db']:.3f}&{v['y_ssim_shave2']:.5f}&{v['lpips_alex_v01']:.5f}" + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    destination = ROOT / "docs/manuscript/figures/classic_training_comparison.tex"
    destination.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {destination}: 24 quality cells")


if __name__ == "__main__":
    main()
